def _finite(value):
    if value is None or isinstance(value, (bool, np.bool_)):
        return None
    try:
        value = float(value)
    except (ValueError, TypeError, OverflowError):
        return None
    return value if math.isfinite(value) else None


def _bool(value):
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if value in (0, 1):
        return bool(value)
    if isinstance(value, str) and value.strip().lower() in ('true', 'false', '1', '0'):
        return value.strip().lower() in ('true', '1')
    raise ValueError('Invalid saved row flag.')


def _configuration(config):
    if not isinstance(config, dict):
        raise ValueError('The saved analysis configuration is missing.')
    result = dict(config)
    for key in ('x_base', 'y_base', 'x_threshold', 'y_threshold'):
        value = _finite(config.get(key))
        if value is None:
            raise ValueError('Invalid saved plot parameter: ' + key)
        result[key] = value
    if result['x_base'] <= 1 or result['y_base'] <= 1:
        raise ValueError('Saved log bases must exceed 1.')
    if result['x_threshold'] < 0 or result['y_threshold'] < 0:
        raise ValueError('Saved plot thresholds must be nonnegative.')
    if config.get('significance_metric') not in ('p', 'q'):
        raise ValueError('Invalid saved significance metric.')
    return result


def legacy_result(csv_bytes, manifest_bytes):
    """Reconstruct display coordinates only; never rerun saved statistical calls."""
    try:
        manifest = json.loads(manifest_bytes.decode('utf-8-sig'))
        if not isinstance(manifest, dict):
            raise ValueError('Invalid saved manifest.')
        config = _configuration(manifest.get('configuration'))
        floor = _finite(manifest.get('method', {}).get('plot_probability_floor', 1e-300))
        if floor is None or not 0 < floor <= 1:
            raise ValueError('Invalid saved probability floor.')
        max_y = -math.log(floor) / math.log(config['y_base'])
        table = csv.DictReader(io.StringIO(csv_bytes.decode('utf-8-sig'), newline=''))
        required = {'row_id', 'protein', 'gene', 'log_fc', 'metric_value', 'significant', 'direction', 'valid', 'excluded'}
        if not required.issubset(table.fieldnames or ()):
            raise ValueError('The saved protein table cannot be exported to MATLAB.')
        rows = []
        for source in table:
            x = _finite(source.get('log_fc'))
            metric = _finite(source.get('metric_value'))
            score = _finite(source.get('significance_score'))
            if score is None and metric is not None and 0 <= metric <= 1:
                score = -math.log(max(metric, floor)) / math.log(config['y_base'])
            y = min(max_y, score) if score is not None else None
            rows.append({**source, 'x': x, 'y': y,
                         **{name: _bool(source[name]) for name in ('significant', 'valid', 'excluded')}})
    except (UnicodeError, json.JSONDecodeError, csv.Error, TypeError, AttributeError) as exc:
        raise ValueError('The saved analysis files are invalid.') from exc
    return {'rows': rows, 'config': config, 'summary': manifest.get('summary', {}),
            'warnings': manifest.get('warnings', []), 'manifest': manifest,
            'export_notes': ['Legacy CSV export: display coordinates reconstructed from saved log_fc and significance_score or metric_value. Saved validity and significance flags were preserved.',
                             'Text and numeric values retain the precision and spreadsheet-safety escaping of the saved CSV.']}


def volcano_bundle_bytes(result):
    """Return a ZIP without touching source files or interpolating source code."""
    config = _configuration(result.get('config'))
    rows = result.get('rows')
    if not isinstance(rows, list) or any(not isinstance(row, dict) for row in rows):
        raise ValueError('Invalid volcano rows.')
    def numeric(key):
        return np.asarray([value if (value := _finite(row.get(key))) is not None else np.nan for row in rows], dtype=float).reshape(-1, 1)
    def strings(key):
        return np.asarray([str(row.get(key) or '') for row in rows], dtype=object).reshape(-1, 1)
    data = {key: numeric(key) for key in ('row_id', 'x', 'y', 'log2_fc', 'log_fc', 'p_value', 'q_value', 'metric_value', 'significance_score')}
    data.update({key: strings(key) for key in ('protein', 'gene', 'description', 'direction', 'exclusion_reason')})
    data.update({key: np.asarray([_bool(row.get(key, False)) for row in rows], dtype=bool).reshape(-1, 1) for key in ('valid', 'significant', 'excluded')})
    data.update({key: config[key] for key in ('x_base', 'y_base', 'x_threshold', 'y_threshold', 'significance_metric')})
    provenance = {'software': "Devil's Proteomics", 'export_format': 'MATLAB Level 5 MAT + MATLAB script',
                  'configuration': config, 'summary': result.get('summary', {}),
                  'warnings': result.get('warnings', []), 'palette': PALETTE,
                  'notes': result.get('export_notes', ['Coordinates and row flags copied directly from the analysis.']),
                  'manifest': result.get('manifest')}
    data['configuration_json'] = json.dumps(config, ensure_ascii=False, allow_nan=False)
    data['summary_json'] = json.dumps(provenance['summary'], ensure_ascii=False, allow_nan=False)
    data['configuration'] = {key: config[key] for key in ('x_base', 'y_base', 'x_threshold', 'y_threshold', 'significance_metric')}
    mat = io.BytesIO()
    savemat(mat, data, do_compression=True, oned_as='column', long_field_names=True)
    package = io.BytesIO()
    with zipfile.ZipFile(package, 'w', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('volcano_data.mat', mat.getvalue())
        archive.writestr('plot_volcano.m', MATLAB_SCRIPT.encode('utf-8'))
        archive.writestr('README.txt', README.encode('utf-8'))
        archive.writestr('provenance.json', json.dumps(provenance, ensure_ascii=False, indent=2, allow_nan=False).encode('utf-8'))
    return package.getvalue()


def write_volcano_bundle(path, result):
    path = Path(path)
    path.write_bytes(volcano_bundle_bytes(result))
    return path
