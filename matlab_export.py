PALETTE = {'up': '#D55E00', 'down': '#0072B2', 'neutral': '#B3B3B3', 'unchanged': '#555555'}

MATLAB_SCRIPT = r"""% Devil's Proteomics: editable volcano figure from saved analysis results.
% MATLAB R2020a or later. No additional toolbox is required.
% Run this script from any working directory; files are read beside the script.
% The saved valid/significant flags are used without recalculating statistics.
base = fileparts(mfilename('fullpath'));
S = load(fullfile(base, 'volcano_data.mat'));
out = fullfile(base, 'matlab_figures');
if ~exist(out, 'dir'), mkdir(out); end
labelCount = 12; % Set to 0 for no labels; increase to label more significant rows.
x = S.x(:); y = S.y(:);
valid = logical(S.valid(:)) & isfinite(x) & isfinite(y);
hit = logical(S.significant(:)) & valid;
direction = string(S.direction(:));
names = string(S.gene(:));
protein = string(S.protein(:));
names(strlength(names) == 0) = protein(strlength(names) == 0);
groups = {valid & ~hit, hit & direction == "down", ...
          hit & direction == "up", hit & direction == "unchanged"};
groupNames = {'Not significant', 'Down', 'Up', 'No fold change'};
colors = [179 179 179; 0 114 178; 213 94 0; 85 85 85] / 255;
fig = figure('Color', 'w', 'Units', 'centimeters', 'Position', [2 2 17.8 13.5]);
ax = axes('Parent', fig); hold(ax, 'on');
set(ax, 'FontName', 'Arial', 'FontSize', 10, 'LineWidth', 0.8, ...
    'TickDir', 'out', 'Box', 'off', 'XGrid', 'off', 'YGrid', 'off');
h = gobjects(0); shown = {};
for k = 1:numel(groups)
    mask = groups{k};
    if any(mask)
        h(end+1) = scatter(ax, x(mask), y(mask), 18, colors(k,:), 'filled', ...
            'MarkerFaceAlpha', 0.85, 'MarkerEdgeColor', 'none'); %#ok<SAGROW>
        shown{end+1} = groupNames{k}; %#ok<SAGROW>
    end
end
if any(valid)
    lim = max(abs(x(valid)));
    if lim == 0, lim = 1; end
    xlim(ax, [-1 1] * lim * 1.08);
    ylim(ax, [0 max(1, max(y(valid))) * 1.10]);
else
    xlim(ax, [-1 1]); ylim(ax, [0 1]);
end
for cutoff = unique([-S.x_threshold S.x_threshold])
    if isfinite(cutoff)
        xline(ax, cutoff, '--', 'Color', [0.35 0.35 0.35], ...
            'LineWidth', 0.8, 'HandleVisibility', 'off');
    end
end
if isfinite(S.y_threshold)
    yline(ax, S.y_threshold, '--', 'Color', [0.35 0.35 0.35], ...
        'LineWidth', 0.8, 'HandleVisibility', 'off');
end
xlabel(ax, sprintf('$\\log_{%g}(\\mathrm{Treatment}/\\mathrm{Control})$', S.x_base), ...
    'Interpreter', 'latex', 'FontSize', 12);
ylabel(ax, sprintf('$-\\log_{%g}(%s)$', S.y_base, char(S.significance_metric)), ...
    'Interpreter', 'latex', 'FontSize', 12);
if ~isempty(h)
    legend(ax, h, shown, 'Location', 'northeast', 'Box', 'off', ...
        'FontName', 'Arial', 'FontSize', 9, 'Interpreter', 'none');
end
% Labels use data, with text interpretation disabled. No identifiers are code.
indices = find(hit);
if ~isempty(indices) && labelCount > 0
    score = S.metric_value(indices); score(~isfinite(score)) = Inf;
    [~, order] = sortrows([score(:), -abs(x(indices)), S.row_id(indices)], [1 2 3]);
    indices = indices(order(1:min(numel(order), floor(labelCount))));
    text(ax, x(indices), y(indices), names(indices), 'Interpreter', 'none', ...
        'FontName', 'Arial', 'FontSize', 8, 'VerticalAlignment', 'bottom', ...
        'HorizontalAlignment', 'left', 'Clipping', 'on');
end
drawnow;
savefig(fig, fullfile(out, 'volcano.fig'));
exportgraphics(fig, fullfile(out, 'volcano.pdf'), 'ContentType', 'vector', 'BackgroundColor', 'white');
print(fig, fullfile(out, 'volcano.svg'), '-dsvg', '-painters');
exportgraphics(fig, fullfile(out, 'volcano.png'), 'Resolution', 600, 'BackgroundColor', 'white');
disp(fullfile(out, 'volcano.fig'));
"""

